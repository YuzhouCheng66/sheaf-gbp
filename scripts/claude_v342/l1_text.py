class Roles(nn.Module):
    """the agents of one role (sender or receiver): two Agents (hetero) or one shared (same)"""

    def __init__(self, agents, pair, max_ctx=None):
        super().__init__()
        self.agents = nn.ModuleList(agents)
        self.idx = [0, 1] if len(agents) == 2 else [0, 0]
        self.pair, self.max_ctx = pair, max_ctx
        self.trunc = {}

    def agent(self, i):
        return self.agents[self.idx[i]]

    @property
    def device(self):
        return self.agents[0].device

    def pieces(self, batch, i, mode, target='answer', messages=None):
        out = []
        for b, ex in enumerate(batch):
            pc, tr = M.make_pieces(self.agent(i), ex, i, mode, self.max_ctx, target, None if messages is None else messages[b])
            self.trunc[tr] = self.trunc.get(tr, 0) + 1
            out.append(pc)
        return out


def build_roles(pair, device, tiny, lora, hf_cache, grad_ckpt, max_ctx, **agent_kw):
    names = M.model_names(pair, 'B0')
    if tiny is not None:
        tn = list(M.TINY_NAMES) if pair == 'hetero' else [M.TINY_NAMES[0]]
        agents = [M.Agent.from_pretrained_objects(tiny[n][0], tiny[n][1], n, lora=lora, comm=False, grad_ckpt=grad_ckpt, **agent_kw) for n in tn]
    else:
        agents = [M.Agent.from_pretrained(n, device, hf_cache, lora=lora, comm=False, grad_ckpt=grad_ckpt, **agent_kw) for n in names]
    return Roles(agents, pair, max_ctx)


def truncate_ids(tok, ids, budget):
    return tok.decode(list(ids)[:budget], skip_special_tokens=True).strip()


def gold_message(tok, ex, i, budget):
    """the gold message written BY agent i (its supporting sentences), cut to the budget with the sender model's tokenizer"""
    return truncate_ids(tok, tok(M.DATA.text_sender_target(ex, i), add_special_tokens=False)['input_ids'], budget)


@torch.no_grad()
def generate_messages(senders, examples, budget, eval_batch, deadline=None, log=None, label=''):
    """-> dict(ids [i][b] (sender token ids, cut at EOS), texts [i][b], seconds_per_example, decode_steps_mean, budget, n)"""
    senders.eval()
    dev = senders.device
    ids = [[None] * len(examples) for _ in range(M.N_AGENTS)]
    steps, t_all = [], 0.0
    for bi, idx in enumerate(M.chunks(list(range(len(examples))), eval_batch)):
        M.check_deadline(deadline, f'messages {label}')
        batch = [examples[j] for j in idx]
        for i in range(M.N_AGENTS):
            ag = senders.agent(i)
            pcs = senders.pieces(batch, i, 'sender', target=None)
            M.sync(dev); t0 = time.perf_counter()
            _, g = ag.generate(pcs, None, budget, want_logits=False, first_line=False)
            M.sync(dev); t_all += time.perf_counter() - t0
            for b, j in enumerate(idx):
                ids[i][j] = g['ids'][b]
            steps += g['steps']
        if log and (bi + 1) % 20 == 0:
            log(f'messages {label}: {(bi + 1) * eval_batch} examples')
    texts = [[truncate_ids(senders.agent(i).tok, r, budget) for r in ids[i]] for i in range(M.N_AGENTS)]
    return dict(ids=ids, texts=texts, seconds_per_example=t_all / max(1, len(examples)), decode_steps_mean=float(np.mean(steps)) if steps else None,
                budget=int(budget), n=len(examples))


def message_record(gen):
    """what messages.json stores per split and budget"""
    return dict(budget=gen['budget'], n=gen['n'], texts=gen['texts'], token_ids=gen['ids'], n_tokens=[[len(r) for r in gen['ids'][i]] for i in range(M.N_AGENTS)],
                seconds_per_example=gen['seconds_per_example'], decode_steps_mean=gen['decode_steps_mean'])


def texts_from_record(rec, toks, budget):
    """the stored messages at a budget <= the stored one (smaller budgets: the stored token ids cut with the sender's tokenizer toks[i])"""
    if budget > rec['budget']:
        raise ValueError(f'budget {budget} > stored {rec["budget"]}')
    if budget == rec['budget']:
        return rec['texts']
    return [[truncate_ids(toks[i], r, budget) for r in rec['token_ids'][i]] for i in range(M.N_AGENTS)]


def message_f1(texts, examples):
    """token F1 of the generated messages against the gold sender targets: overall and per agent"""
    per = [[float(M.DATA.f1_score(texts[i][j], M.DATA.text_sender_target(ex, i))) for j, ex in enumerate(examples)] for i in range(M.N_AGENTS)]
    return dict(overall=float(np.mean([x for p in per for x in p])) if examples else None, agent=[float(np.mean(p)) if p else None for p in per])


@torch.no_grad()
def eval_text(receivers, examples, messages, eval_batch, max_new_tokens, drop_p=0.0, seed=0, deadline=None, keep_preds=False, log=None, label=''):
    """messages[i][b] = the message written by agent i; receiver i reads messages[1 - i][b] ('' when dropped with probability drop_p)"""
    receivers.eval()
    dev = receivers.device
    g = torch.Generator().manual_seed(int(seed) * 1009 + int(round(drop_p * 100)))
    recs, t_gen, n_drop = [], 0.0, 0
    receivers.trunc.clear()
    msg_f1 = []
    for bi, idx in enumerate(M.chunks(list(range(len(examples))), eval_batch)):
        M.check_deadline(deadline, f'eval_text {label}')
        batch = [examples[j] for j in idx]
        drop = (torch.rand(M.N_AGENTS, len(batch), generator=g) < drop_p)
        n_drop += int(drop.sum())
        for i in range(M.N_AGENTS):
            ag = receivers.agent(i)
            msgs = ['' if bool(drop[i, b]) else messages[1 - i][j] for b, j in enumerate(idx)]
            pcs = receivers.pieces(batch, i, 'receiver', target=None, messages=msgs)
            M.sync(dev); t0 = time.perf_counter()
            texts, gi = ag.generate(pcs, None, max_new_tokens, want_logits=True)
            M.sync(dev); t_gen += time.perf_counter() - t0
            for b, ex in enumerate(batch):
                ent = float(gi['first_token_entropy'][b]) if gi['first_token_entropy'] is not None else None
                r = M._record(ex, i, ag.name, texts[b], gi['steps'][b], ent)
                r['message_len_chars'] = len(msgs[b])
                recs.append(r)
                if drop_p == 0.0:
                    msg_f1.append(M.DATA.f1_score(messages[i][idx[b]], M.DATA.text_sender_target(ex, i)))
        if log and (bi + 1) % 20 == 0:
            log(f'eval {label}: {len(recs)} records')
    out = M.summarise(recs)
    out.update(drop_p=drop_p, n_messages_dropped=n_drop, n_messages=M.N_AGENTS * len(examples), answer_gen_s_per_example=t_gen / max(1, len(recs)),
               truncation=dict(receivers.trunc), message_f1_vs_gold=(float(np.mean(msg_f1)) if msg_f1 else None),
               message_chars_mean=float(np.mean([r['message_len_chars'] for r in recs])) if recs else None)
    if keep_preds:
        out['records'] = recs
    return out


