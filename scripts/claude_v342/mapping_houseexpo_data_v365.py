"""HouseExpo world family v365 for the Sheaf-GBP mapping experiments (Claude, 2026-10-22).

ONE change versus the sealed v293 corridor-spine family: the world geometry. Everything else is the v293 public frame:
20 m x 20 m chart, raster[row=y, col=x], native H in {128, 256, 512}, three short jittered poses per agent, first-hit DDA rays
(v293.observe_trajectory: 256 beams, strict 5 m), static 8 m radio (v121.radius_adjacency), N in {8, 16}.

Geometry: the official HouseExpo `verts` contour encloses FREE floor; everything else is occupied (as in the v121 adapter). Houses
with extent <= 19 m (both axes) and room_num >= 2 are eligible; each is translated so its bbox centre is the chart centre (no crop,
no resizing). Rasterisation is conservative: a cell is free iff all 4x4 supersamples are inside the contour (thin walls survive).

Splits: by the exact contour hash (translation / cyclic order / reversal invariant; v121.geometry_hash), so exact duplicates share a
split: TRAIN 80 %, VALIDATION 10 %, TEST 10 %. TEST is never generated by this module (world_spec raises). Near duplicates and rotated
copies are NOT detected (stated limitation).
Strata ('rooms' field): 1 = 2-4 rooms, 2 = 5-7 rooms, 3 = 8+ rooms (HouseExpo room_num).
Doors: HouseExpo has no door annotation. evaluation['door_mask'] is an OPENING mask: free cells of an axis-aligned free run bounded
by occupied cells on both ends, 0.4-1.5 m wide, whose component extends <= 0.6 m across the run (an opening through a wall, not a
corridor). Metrics computed with it must be reported as 'opening free recall', not door recall.
Poses: centres sampled uniformly over the largest 4-connected free component with >= 0.45 m clearance (computed on the 512 raster, so
poses are free at every native size), >= 1.0 m apart where possible; deltas uniform in +-0.10 m; deterministic from the house id.

Index file: build_index(json_dir) writes houseexpo_index_v365.json (id, contour hash, split, stratum, extent, room_num) once.
Environment: HOUSEEXPO_JSON_DIR (extracted json/ directory) and HOUSEEXPO_INDEX (index file) must be set.
"""
import hashlib, json, os
from collections import deque
import numpy as np
from PIL import Image, ImageDraw
