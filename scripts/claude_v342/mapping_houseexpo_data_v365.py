from scripts import mapping_multiroom_data_v293 as d293
from scripts.prepare_houseexpo_pilot_v121 import radius_adjacency, geometry_hash

VERSION = 365
EXTENT = 20.
SIZES = (128, 256, 512)
AGENT_COUNTS = (8, 16)
STRATA = {1: (2, 4), 2: (5, 7), 3: (8, 10 ** 6)}
MAX_EXTENT = 19.
INPUT_FIELDS = ('private', 'positions_m', 'trajectory_m', 'adjacency')


def _seed(text):
    return int.from_bytes(hashlib.sha256(text.encode()).digest()[:8], 'little')


def array_hash(value):
    return d293.array_hash(value)


def build_index(json_dir, out_path):
    import glob
    rows = []
    for f in sorted(glob.glob(os.path.join(json_dir, '*.json'))):
        d = json.load(open(f))
        v = np.asarray(d.get('verts', []), dtype=np.float64)
        if v.ndim != 2 or v.shape[1:] != (2,) or len(v) < 3 or not np.isfinite(v).all():
            continue
        ext = np.ptp(v, 0)
        rn = int(d.get('room_num', 0))
        if ext.max() > MAX_EXTENT or rn < 2 or ext.min() < 2.:
            continue
        gh = geometry_hash(v)
        b = _seed(f'v365:split:{gh}') % 10
        split = 'TRAIN' if b < 8 else ('VALIDATION' if b == 8 else 'TEST')
        stratum = next(s for s, (lo, hi) in STRATA.items() if lo <= rn <= hi)
        rows.append(dict(id=d['id'], contour_sha256=gh, split=split, stratum=stratum, room_num=rn, extent_m=[float(ext[0]), float(ext[1])]))
    # exact duplicates: keep one representative per contour hash (lowest id)
    seen = {}
    for r in sorted(rows, key=lambda r: r['id']):
        seen.setdefault(r['contour_sha256'], r)
    rows = sorted(seen.values(), key=lambda r: _seed(f'v365:order:{r["id"]}'))
    idx = dict(version=VERSION, source='HouseExpo json.tar.gz sha256 dad4a7d230937bdfe1d57c91330e697b625ec681eefd9cda3159082a939b4f2f',
               filters=dict(max_extent_m=MAX_EXTENT, min_rooms=2, min_extent_m=2.), strata={str(k): list(v) for k, v in STRATA.items()},
               counts={sp: {str(s): sum(1 for r in rows if r['split'] == sp and r['stratum'] == s) for s in STRATA} for sp in ('TRAIN', 'VALIDATION', 'TEST')},
               houses=[r for r in rows if r['split'] != 'TEST'],
               test_houses_withheld=sum(1 for r in rows if r['split'] == 'TEST'))
    json.dump(idx, open(out_path, 'w'))
    return idx


_INDEX = None


def _index():
    global _INDEX
    if _INDEX is None:
        _INDEX = json.load(open(os.environ['HOUSEEXPO_INDEX']))
        lists = {}
        for r in _INDEX['houses']:
            lists.setdefault((r['split'], r['stratum']), []).append(r)
        _INDEX['lists'] = lists
    return _INDEX


def world_spec(split, index, rooms=1):
    split = str(split).upper()
    if split not in ('TRAIN', 'VALIDATION'):
        raise ValueError('Only TRAIN/VALIDATION, never TEST')
    lst = _index()['lists'][(split, int(rooms))]
    rec = lst[int(index)]
    d = json.load(open(os.path.join(os.environ['HOUSEEXPO_JSON_DIR'], rec['id'] + '.json')))
    v = np.asarray(d['verts'], dtype=np.float64)
    if geometry_hash(v) != rec['contour_sha256']:
        raise ValueError('house contour does not match the index')
    centre = (v.min(0) + v.max(0)) / 2
    verts = v - centre + EXTENT / 2
    return dict(version=VERSION, family='houseexpo', split=split, index=int(index), stratum=int(rooms), house_id=rec['id'],
                world_id=f'v365:{split}:{rec["id"]}', room_num=rec['room_num'], verts_m=verts.tolist(), contour_sha256=rec['contour_sha256'],
                occupancy='inside the HouseExpo contour is free; complement is occupied', coordinate_convention='metric(x,y); raster[row=y,column=x]')


def rasterize(spec, size, supersample=4):
    if size not in SIZES:
        raise ValueError('native size required')
    cell = EXTENT / size
    pix = np.asarray(spec['verts_m']) / cell * supersample
    img = Image.new('L', (size * supersample, size * supersample), 0)
    ImageDraw.Draw(img).polygon([tuple(p) for p in pix], fill=1)
    s = np.asarray(img, dtype=np.uint8)
    free = s.reshape(size, supersample, size, supersample).min(axis=(1, 3)) != 0
    walls = (~free).astype(np.int8)
    return dict(walls=walls, door_mask=narrow_mask(walls, cell))


def narrow_mask(walls, cell, lo=.4, hi=1.5, max_thick=.6):
    """Doorway-like openings: free cells in an axis-aligned free run bounded by occupied cells on both ends with width in [lo, hi]
    metres, AND the connected component of such cells extends at most `max_thick` metres across the run direction (an opening
    through a wall, not a corridor). HouseExpo has no door labels; this is a geometric proxy, reported as 'opening recall'."""
    free = walls == 0
    out = np.zeros_like(free)
    for transpose in (False, True):
        arr = free.T if transpose else free
        m = np.zeros_like(arr)
        for r in range(arr.shape[0]):
            row = arr[r]; c = 0; n = len(row)
            while c < n:
                if not row[c]:
                    c += 1; continue
                start = c
                while c < n and row[c]:
                    c += 1
                if start > 0 and c < n and lo <= (c - start) * cell <= hi:
                    m[r, start:c] = True
        lab, k = ndimage.label(m)
        for sl_i, sl in enumerate(ndimage.find_objects(lab), 1):
            if sl is not None and (sl[0].stop - sl[0].start) * cell <= max_thick:   # thickness across the run (rows of arr)
                out |= ((lab == sl_i).T if transpose else (lab == sl_i))
    return out


def metric_trajectory(spec, agents=8):
    if agents not in AGENT_COUNTS:
        raise ValueError('agents')
    rng = np.random.default_rng(_seed(spec['world_id'] + f':poses:{agents}'))
    fine = rasterize(spec, 512)['walls'] == 0
    lab, nlab = ndimage.label(fine)
    if nlab == 0:
        raise ValueError('no free space')
    sizes = ndimage.sum(np.ones_like(lab), lab, index=np.arange(1, nlab + 1))
    comp = lab == (1 + int(np.argmax(sizes)))
    cell = EXTENT / 512
    clearance = ndimage.distance_transform_edt(fine) * cell
    cand = np.argwhere(comp & (clearance >= .45))
    if len(cand) < agents:
        raise ValueError('not enough free space with clearance')
    centres = []
    order = rng.permutation(len(cand))
    for min_sep in (1.0, .5, 0.):
        centres = []
        for i in order:
            rc = cand[i]; p = np.array([(rc[1] + .5) * cell, (rc[0] + .5) * cell])
            if all(np.linalg.norm(p - q) >= min_sep for q in centres):
                centres.append(p)
            if len(centres) == agents:
                break
        if len(centres) == agents:
            break
    centres = np.asarray(centres)
    deltas = rng.uniform(-.10, .10, (agents, 2))
    return centres[None] + np.array([-1., 0., 1.])[:, None, None] * deltas[None]


def make_fixture(split, index, size=128, rooms=1, agents=8):
    spec = world_spec(split, index, rooms)
    geometry = rasterize(spec, size)
    trajectory = metric_trajectory(spec, agents)
    private, rc, snapped = d293.observe_trajectory(geometry['walls'], trajectory)
    adjacency = radius_adjacency(trajectory[-1], d293.RADIO_RADIUS)
    frame = dict(origin_m=[0., 0.], extent_m=[20., 20.], shape=[size, size], cell_size_m=EXTENT / size,
                 coordinate_convention='pose=(x,y); raster=[y,x]', sensor_range_m=d293.SENSOR_RANGE, sensor_beams=256,
                 communication_radius_m=d293.RADIO_RADIUS, static_snapshot=True, radio_occlusion=False)
    inputs = dict(private=private.copy(), positions_m=trajectory[-1].copy(), trajectory_m=trajectory.copy(), adjacency=adjacency.copy(), public_frame=frame)
    evaluation = dict(door_mask=geometry['door_mask'] & (private != 1).all(0), walls=geometry['walls'], geometry_spec=dict(spec, verts_m=None))
    manifest = dict(version=VERSION, world_id=spec['world_id'], house_id=spec['house_id'], split=split, index=int(index), stratum=int(rooms),
                    agents=agents, size=size, private_sha256=array_hash(private), trajectory_sha256=array_hash(trajectory),
                    door_mask_semantics='opening 0.4-1.5 m wide through a wall <= 0.6 m thick (HouseExpo has no door labels)', TEST_opened=False)
    return dict(inputs=inputs, evaluation=evaluation, manifest=manifest)


def scene_plan(split, size=None, train_per_stratum=200):
    split = str(split).upper()
    if split not in ('TRAIN', 'VALIDATION'):
        raise ValueError('TEST is closed')
    sizes = SIZES if size is None else (size,)
    if split == 'TRAIN':
        # distinct houses, one agent count each (alternating), equal per stratum
        return [dict(split=split, index=i, rooms=s, agents=(8 if i % 2 == 0 else 16), size=h) for h in sizes for s in STRATA for i in range(train_per_stratum)]
    return [dict(split=split, index=i, rooms=s, agents=n, size=h) for h in sizes for s in STRATA for n in AGENT_COUNTS for i in range(8)]
