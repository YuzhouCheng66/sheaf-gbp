"""TRAIN cache for the v420 storey world (Claude, 2026-10-25): one compressed npz per TRAIN scene (private int8 [N, NX, NY, NZ],
reached [H, N, N], edges, positions, chart side) plus manifest.json (per-row private sha256, data module sha256, dims, hops). Scenes are
generated in a spawn pool (incident D6-3: never fork after threads exist). TRAIN only; VALIDATION is generated by the trainer, TEST never.
python gen_3d_cache_v420.py --source <sealed> --out DIR --per-stratum 1600 --dims 128,128,32 --workers 8
"""
import argparse, hashlib, json, multiprocessing, os, sys, time
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parent


def _init(source):
    sys.path.insert(0, source); sys.path.insert(0, os.path.join(source, 'exploration_grid')); sys.path.insert(0, str(HERE))


def _one(job):
    spec, out = job
    import mapping_3d_storey_data_v420 as W
    fx = W.make_fixture(spec['split'], spec['index'], spec['rooms'], tuple(spec['dims']), spec['agents'])
    fn = f"r{spec['rooms']}-i{spec['index']:05d}.npz"
    np.savez_compressed(Path(out) / fn, private=fx['private'], reached=fx['reached'], edges=np.array(fx['edges'], dtype=np.float64).reshape(-1, 3),
                        positions_m=fx['positions_m'], chart_m=fx['chart_m'])
    return dict(file=fn, spec=spec, private_sha256=W.array_hash(fx['private']), edges=len(fx['edges']), n_objects=fx['n_objects'],
                known_fraction=float((fx['private'] >= 0).mean()), chart_m=fx['chart_m'])


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--source', required=True); ap.add_argument('--out', required=True)
    ap.add_argument('--per-stratum', type=int, default=1600); ap.add_argument('--dims', default='128,128,32'); ap.add_argument('--workers', type=int, default=8)
    args = ap.parse_args()
    _init(args.source)
    import mapping_3d_storey_data_v420 as W
    dims = [int(x) for x in args.dims.split(',')]
    out = Path(args.out); out.mkdir(parents=True, exist_ok=False)
    plan = W.scene_plan('TRAIN', args.per_stratum, dims)
    rows = []; t0 = time.time(); bad = []
    with multiprocessing.get_context('spawn').Pool(args.workers, initializer=_init, initargs=(args.source,)) as pool:
        for r in pool.imap(_safe, [(s, str(out)) for s in plan], chunksize=4):
            if 'error' in r:
                bad.append(r)
            else:
                rows.append(r)
            if (len(rows) + len(bad)) % 200 == 0:
                print(f'{len(rows) + len(bad)}/{len(plan)} ({len(bad)} skipped) {time.time()-t0:.0f}s', flush=True)
    mod = W.__file__
    json.dump(dict(script='gen_3d_cache_v420.py', script_sha256=hashlib.sha256(open(__file__, 'rb').read()).hexdigest(), version=W.VERSION, dims=dims, agents=W.AGENTS,
                   hops=list(W.HOPS), per_stratum=args.per_stratum, scenes=len(rows), skipped=bad, data_module_sha256=hashlib.sha256(open(mod, 'rb').read()).hexdigest(),
                   seconds=time.time() - t0, rows=rows), open(out / 'manifest.json', 'w'), indent=1)
    print('done', len(rows), 'scenes', len(bad), 'skipped', f'{time.time()-t0:.0f}s')


def _safe(job):
    try:
        return _one(job)
    except ValueError as e:                                                  # only agent placement may skip a house (review v420 S7)
        return dict(spec=job[0], error=repr(e)[:200])


if __name__ == '__main__':
    main()
